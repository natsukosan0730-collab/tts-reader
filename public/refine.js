// TTS向けテキスト整形（ルールベース、APIは使わない）
// 目的: 読み上げで「記号を読む」「不自然に途切れる」「無音が入る」原因を取り除く
export function refineText(input) {
  let t = input.replace(/\r\n?/g, '\n');

  // 1. コードブロックは読み上げ不能なので除去
  t = t.replace(/```[\s\S]*?```/g, '\n');
  t = t.replace(/`([^`]*)`/g, '$1');

  // 2. Markdown: リンクは表示文字のみ、見出し・箇条書き・強調記号を除去
  t = t.replace(/!\[[^\]]*\]\([^)]*\)/g, '');
  t = t.replace(/\[([^\]]+)\]\((?:https?:\/\/)[^)]*\)/g, '$1');
  t = t.replace(/^\s{0,3}#{1,6}\s+/gm, '');
  t = t.replace(/^\s*(?:[-*+•・●○■□▪▶▷◆◇]|\d+[.)]|[（(]\d+[）)])\s+/gm, '');
  t = t.replace(/(\*\*|__|~~)/g, '');
  t = t.replace(/^\s*>+\s?/gm, '');
  t = t.replace(/^\s*(?:[-*_=─━―]{3,})\s*$/gm, '');

  // 3. URLは「リンク」に置換、メールアドレスは除去（読み上げても意味がないため）
  t = t.replace(/https?:\/\/[^\s)）」』]+/g, 'リンク');
  t = t.replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, '');

  // 4. 脚注番号・参照記号 [1] [注1] ［1］ を除去
  t = t.replace(/[\[［](?:注|\*)?\d+(?:[,，、-]\d+)*[\]］]/g, '');

  // 5. 絵文字・装飾記号を除去
  t = t.replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{200B}-\u{200D}\u{2B00}-\u{2BFF}]/gu, '');
  t = t.replace(/[▼▲△▽◎★☆※→←↑↓⇒⇔]/g, '');

  // 6. 全角英数字を半角に（読み間違い・発音のばらつきを防ぐ）
  t = t.replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));

  // 7. 数値範囲の「~」「〜」は「から」と読ませる
  t = t.replace(/(\d)\s*[~〜～]\s*(\d)/g, '$1から$2');

  // 8. 連続する記号の圧縮（無音や不自然な間の原因）
  t = t.replace(/[。]{2,}/g, '。').replace(/[、]{2,}/g, '、');
  t = t.replace(/[!！]{2,}/g, '！').replace(/[?？]{2,}/g, '？');
  t = t.replace(/[…]{2,}|[.]{4,}|[・]{3,}/g, '…');
  t = t.replace(/[ー－―]{3,}/g, 'ー');

  // 9. 行単位の整理: ページ番号だけの行・空行を削除し、行頭行末の空白を除去
  const lines = t
    .split('\n')
    .map((l) => l.replace(/[ \t　]+/g, ' ').trim())
    .filter((l) => l && !/^[-–—\s]*\d{1,4}[-–—\s]*$/.test(l));

  // 10. 句点のない行（見出しなど）に「。」を補い、読み上げで自然な間を作る
  const out = lines.map((l) => (/[。！？!?.…」』）)]$/.test(l) ? l : l + '。'));

  // 日本語どうしの間の余計な半角スペースを除去
  return out
    .join('\n')
    .replace(/([぀-ヿ㐀-鿿]) ([぀-ヿ㐀-鿿])/g, '$1$2')
    .trim();
}
